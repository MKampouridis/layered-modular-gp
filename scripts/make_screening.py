"""Write the WP2 screening campaign from the tuned configurations, and after
the runs, apply the G2 test.

  python scripts/make_screening.py write [--seeds 10]
  python scripts/make_screening.py g2 --results results/screening --arm a5

G2 (research plan): a hierarchical arm beats tree GP at two or more budgets
on at least half the Stage 1 tasks. Per task and budget: one-sided
Mann-Whitney U on test error (regression: test MSE; Boolean: final training
error, the task being the whole truth table), Holm-corrected over the
budgets of that task; "beats" needs p < 0.05 and a lower median than A1.
The arm tested is fixed before the runs (--arm, chosen from the tuning).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from lmgp.run.config import expand_batch, run_id, task_label  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "configs" / "wp2"
ARMS = ["a1", "a2", "a3", "a3_lb1", "a3_lbmax", "a4", "a5", "a6", "a6_inputs"]
BUDGETS = [1e8, 1e9, 1e10, 1e11]


def stage1_tasks():
    tasks = [{"kind": "comp", "levels": L, "reuse": R, "noise": z, "instance": 0}
             for L in (1, 2, 3, 4) for R in (1, 2, 3, 4) for z in (0.0, 0.01, 0.1)]
    tasks += [{"kind": "parity", "n": n} for n in (5, 6, 7, 8)]
    tasks += [{"kind": "mux", "k": 3}]  # 11-multiplexer; the 20-multiplexer waits for WP3
    return tasks


def write(seeds: int):
    tuned = yaml.safe_load((OUT / "tuned.yaml").read_text())
    missing = [a for a in ARMS if a not in tuned]
    if missing:
        raise SystemExit(f"no tuned configuration for {missing}: run the tuning first")
    cases = [{"arm": a, "arm_params": tuned[a]["arm_params"]} for a in ARMS]
    batch = {"base": {"pop_size": "auto", "max_generations": 10 ** 9},
             "cases": cases, "grid": {"budget": BUDGETS, "task": stage1_tasks()}, "seeds": seeds}
    (OUT / "screening.yaml").write_text(
        "# WP2 screening, generated by scripts/make_screening.py from configs/wp2/tuned.yaml.\n"
        + yaml.safe_dump(batch, sort_keys=False))
    print(f"{len(expand_batch(batch))} runs -> {OUT / 'screening.yaml'}")


def holm(p):
    p = np.asarray(p, float)
    order = np.argsort(p)
    adj = np.empty_like(p)
    m, run = len(p), 0.0
    for i, k in enumerate(order):
        run = max(run, (m - i) * p[k])
        adj[k] = min(1.0, run)
    return adj


def g2(results: str, arm: str, alpha=0.05):
    from scipy.stats import mannwhitneyu

    batch = yaml.safe_load((OUT / "screening.yaml").read_text())
    rows = []
    for cfg in expand_batch(batch):
        if cfg["arm"] not in ("a1", arm):
            continue
        f = Path(results) / run_id(cfg) / "final.parquet"
        if f.exists():
            r = pd.read_parquet(f).iloc[0]
            boolean = cfg["task"]["kind"] in ("parity", "mux")
            rows.append({"arm": cfg["arm"], "task": task_label(cfg["task"]), "budget": cfg["budget"],
                         "err": float(r["best_train"] if boolean else r["test_mse"])})
    df = pd.DataFrame(rows)
    out, wins = [], {}
    for task, g in df.groupby("task"):
        ps, meds = [], []
        for b in BUDGETS:
            x = g[(g.arm == arm) & (g.budget == b)].err.values
            y = g[(g.arm == "a1") & (g.budget == b)].err.values
            if len(x) and len(y) and np.unique(np.concatenate([x, y])).size > 1:
                p = mannwhitneyu(x, y, alternative="less").pvalue
            else:
                p = 1.0
            ps.append(p)
            meds.append((np.median(x) if len(x) else np.nan, np.median(y) if len(y) else np.nan))
        adj = holm(ps)
        n_win = 0
        for b, p, q, (mx, my) in zip(BUDGETS, ps, adj, meds):
            win = q < alpha and mx < my
            n_win += win
            out.append({"task": task, "budget": b, f"median_{arm}": mx, "median_a1": my, "p": p,
                        "p_holm": q, "beats_a1": win})
        wins[task] = n_win
    table = pd.DataFrame(out)
    n_pass = sum(v >= 2 for v in wins.values())
    verdict = n_pass >= len(wins) / 2
    print(table.to_string(index=False, float_format=lambda v: f"{v:.3g}"))
    print(f"\n{arm} beats A1 at >= 2 budgets on {n_pass} of {len(wins)} tasks -> G2 {'PASS' if verdict else 'FAIL'}")
    return table, verdict


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", choices=["write", "g2"])
    ap.add_argument("--seeds", type=int, default=10)
    ap.add_argument("--results", default="results/screening")
    ap.add_argument("--arm", default="a5")
    a = ap.parse_args()
    write(a.seeds) if a.mode == "write" else g2(a.results, a.arm)
